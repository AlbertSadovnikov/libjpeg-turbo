#!/usr/bin/env python3
"""Derive arithmetic variants, diagonal compensation, and range certificates.

Generation and verification use only the Python standard library. Compensation
fits the analytical DCT basis, not the camera frames. No image data are used.
"""
import importlib.util
import json
import math
from pathlib import Path
import sys
from fractions import Fraction as F
sys.dont_write_bytecode=True
spec=importlib.util.spec_from_file_location('idct_bounds',Path(__file__).with_name('luma-idct-bound.py'))
bounds=importlib.util.module_from_spec(spec);spec.loader.exec_module(bounds)
NAMES=['comp-control','root-3over2','root-45over32','rotation-1-3over8','root-and-rotation','modular','root-91over64','root-181over128']

def transform(x, mode, frac, shift):
    def root(a):
        if mode in (1,4): return a+shift(a,1)
        if mode==2: return a+shift(a,1)-shift(a,4)-shift(a,5)
        if mode==6: return a+shift(a,1)-shift(a,4)-shift(a,6)
        if mode==7: return a+shift(a,1)-shift(a,4)-shift(a,6)-shift(a,7)
        return a+frac(a,13573)
    p=x[0]+x[4];q=x[0]-x[4];r=x[2]+x[6]
    t=root(x[2]-x[6])-r
    e0=p+r;e3=p-r;e1=q+t;e2=q-t
    a=x[5]+x[3];b=x[5]-x[3];c=x[1]+x[7];d=x[1]-x[7]
    o7=c+a;u=root(c-a)
    if mode in (3,4):
        sine=lambda a:shift(a,1)-shift(a,3)
        v=d-sine(b);w=b+sine(d)
    else:
        v=frac(d,30274)-frac(b,12540)
        w=frac(b,30274)+frac(d,12540)
    o6=v+v-o7;o5=u-o6;o4=w+w-o5
    return [e0+o7,e1+o6,e2+o5,e3+o4,e3-o4,e2-o5,e1-o6,e0-o7]

def derive(mode):
    bounds.nodes.clear();checkpoints=[]
    def frac(a,c):
        checkpoints.append(a)
        return a.frac(c)
    def shift(a,n):
        factor=F(1,1<<n)
        checkpoints.append(a)
        return bounds.Affine([v*factor for v in a.a],a.error*factor+1-factor)
    x=[[bounds.Affine([int(k==r*8+c) for k in range(64)]) for c in range(8)] for r in range(8)]
    for c in range(8):
        col=transform([x[r][c] for r in range(8)],mode,frac,shift)
        for r in range(8):x[r][c]=col[r]
    for r in range(8):x[r]=transform(x[r],mode,frac,shift)
    final=[a for row in x for a in row]
    required=checkpoints+final if mode==5 else bounds.nodes
    weights=[math.ceil(max(abs(a.a[k]) for a in required)) for k in range(64)]
    error=max(a.error for a in required)
    gain=max(sum(abs(v) for v in a.a) for a in bounds.nodes)
    assert gain<256 and math.ceil(error)<=256
    assert (256*(1<<30)+256)*32768+(1<<15)<(1<<63)
    # Quantization compensation: independent least-squares scale per frequency.
    scales=[];squared=0
    for k in range(8):
        column=transform([float(j==k) for j in range(8)],mode,lambda a,c:a*c/32768,lambda a,n:a/(1<<n))
        target=[1 if k==0 else math.sqrt(2)*math.cos((2*r+1)*k*math.pi/16) for r in range(8)]
        scale=sum(a*b for a,b in zip(column,target))/sum(a*a for a in column)
        if mode==5:scale=1 if k==0 else math.sqrt(2)*math.cos(k*math.pi/16)
        scales.append(scale)
        squared+=sum((a*scale-b)**2 for a,b in zip(column,target))
    return dict(name=NAMES[mode],weights=weights,error=math.ceil(error),error_exact=str(error),gain=float(gain),scales=scales,basis_rmse=math.sqrt(squared/64))

def main():
    variants=[derive(mode) for mode in range(len(NAMES))]
    header=Path(__file__).with_name('luma-idct-arithmetic-tables.h')
    text='// Generated by luma-idct-arithmetic.py --generate; do not edit.\n#pragma once\n'
    text+='static constexpr short arithmetic_weights[8][64]={\n'+',\n'.join('  {'+','.join(map(str,v['weights']))+'}' for v in variants)+'\n};\n'
    text+='static constexpr int arithmetic_errors[8]={'+','.join(str(v['error']) for v in variants)+'};\n'
    text+='static constexpr double arithmetic_scales[8][8]={\n'+',\n'.join('  {'+','.join(format(s,'.17g') for s in v['scales'])+'}' for v in variants)+'\n};\n'
    text+='static constexpr const char *arithmetic_names[8]={'+','.join(json.dumps(v['name']) for v in variants)+'};\n'
    if '--generate' in sys.argv:header.write_text(text)
    else:assert header.read_text()==text,'Regenerate arithmetic tables'
    for v in variants:
        for bits in (2,3,4):
            limit=32767-v['error']-(1<<(bits+2))
            assert limit+F(v['error_exact'])+(1<<(bits+2))<=32767
        print(v['name'],'error <=',v['error'],'gain',round(v['gain'],4),'basis RMSE',round(v['basis_rmse'],6))
    # Modular variant deliberately allows wrapping only between nonlinear inputs
    # and final outputs. Wide add/sub and 16-bit add/sub agree modulo 2^16.
    print('All eight range certificates and diagonal compensation tables verified')

if __name__=='__main__':main()
